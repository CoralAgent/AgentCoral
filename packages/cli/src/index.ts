onchain
  .command("send")
  .description("gated transfer from the signer wallet — paper by default; live needs -m live --confirm")
  .argument("<token>", "ETH, USDG, CORAL, or a 0x token address")
  .argument("<amount>", "amount in human units")
  .argument("<to>", "recipient 0x address")
  .option("--confirm", "broadcast for real (live mode only)")
  .option("--json", "machine-readable output")
  .action(async (tokenArg: string, amount: string, to: string, opts: { confirm?: boolean; json?: boolean }) => {
    const rt = boot(program.opts().mode ? { mode: program.opts().mode } : {});
    if (!opts.json) banner();
    const out = (code: number, payload: Record<string, unknown>) => {
      if (opts.json) console.log(JSON.stringify(payload, null, 2));
      rt.close();
      process.exit(code);
    };

    const sw = createSigner(rt.config);
    if (!sw.signer) out(1, { error: sw.reason });
    const signer = sw.signer;
    if (!isAddress(to)) out(1, { error: `bad recipient: ${to}` });
    const amountNum = Number(amount);
    if (!Number.isFinite(amountNum) || amountNum <= 0) out(1, { error: `bad amount: ${amount}` });

    const known = KNOWN_TOKENS[tokenArg.toUpperCase()];
    const isNative = tokenArg.toUpperCase() === "ETH";
    const tokenAddr = isNative ? null : ((known?.address ?? (isAddress(tokenArg) ? tokenArg : null)) as Address | null);
    if (!isNative && !tokenAddr) out(1, { error: `unknown token: ${tokenArg} — pass a 0x address` });
    const decimals = isNative ? 18 : (known?.decimals ?? 18);
    const symbol = isNative ? "ETH" : (known ? tokenArg.toUpperCase() : tokenArg.slice(0, 10));

    // price the send for the risk gate: stables ~$1, else try an Chainbridge quote
    let notionalUsd = STABLES.has(symbol) ? amountNum : NaN;
    if (!Number.isFinite(notionalUsd)) {
      try {
        await rt.oak.connect();
        const info = await rt.oak.resolveToken(isNative ? "ETH" : (tokenAddr as string));
        const unit = await rt.oak.quote({ from: info.address, to: KNOWN_TOKENS.USDG!.address, amountIn: toBaseUnits("1", info.decimals) });
        notionalUsd = amountNum * Number(unit.output?.humanAmount ?? "NaN");
      } catch { /* priced below */ }
    }
    if (!Number.isFinite(notionalUsd) || notionalUsd <= 0) {
      out(1, { error: `cannot price ${symbol} for the risk gate — refusing to send blind` });
    }

    const verdict = rt.risk.review(
      {
        decision: {
          symbol,
          action: "sell",
          confidence: 1,
          thesis: `manual send ${amount} ${symbol} → ${to}`,
          tags: ["onchain", "send", "manual"],
          recalled: [],
        },
        price: notionalUsd / amountNum,
        requestedNotional: notionalUsd,
      },
      { ...rt.engine.riskStateFor(symbol), mode: rt.config.mode },
    );

    const live = rt.config.mode === "live";
    let effectiveAmount = amount;
    if (verdict.scaledFrom !== undefined && notionalUsd > 0) {
      effectiveAmount = (amountNum * (verdict.notional / notionalUsd)).toPrecision(12);
    }
    const payload: Record<string, unknown> = {
      stage: "quoted",
      from: signer!.address,
      to,
      token: symbol,
      amount: effectiveAmount,
      notionalUsd: Number(verdict.notional.toFixed(2)),
      gate: verdict.allowed ? "pass" : "blocked",
      reasons: verdict.reasons,
      mode: rt.config.mode,
      ...(effectiveAmount !== amount ? { note: `scaled ${amount} → ${effectiveAmount} to honour risk cap` } : {}),
    };

    if (!verdict.allowed) {
      payload.stage = "rejected";
      out(2, payload);
    }
    if (!live || !opts.confirm) {
      payload.stage = "dry-run";
      if (!opts.json) {
        heading(`Send · ${amount} ${symbol} → ${to.slice(0, 10)}…`);
        keyValue([
          ["gate", verdict.allowed ? c.green("pass") : c.red("blocked")],
          ["notional", `$${notionalUsd.toFixed(2)}`],
          ["mode", live ? c.red("live") : c.teal("paper")],
        ]);
        console.log(`\n  ${c.dim("dry run — re-run with -m live --confirm to broadcast.")}\n`);
      }
      out(0, payload);
    }

    try {
      const hash = isNative
        ? await signer!.sendNative(to as Address, effectiveAmount)
        : await signer!.sendErc20(tokenAddr as Address, to as Address, effectiveAmount, decimals);
      payload.stage = "broadcast";
      payload.txHash = hash;
      if (!opts.json) {
        heading(`Sent · ${amount} ${symbol}`);
        keyValue([["tx", c.green(hash)], ["gate", c.green("pass")], ["notional", `$${notionalUsd.toFixed(2)}`]]);
        console.log();
      }
      out(0, payload);
    } catch (err) {
      payload.stage = "error";
      payload.error = err instanceof Error ? err.message.slice(0, 200) : String(err);
      out(3, payload);
    }
  });

