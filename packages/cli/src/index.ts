program
  .command("backtest")
  .description("replay real historical bars through the real decide→gate→fill loop")
  .argument("<symbol>", "equity symbol, or token symbol/address with --oak")
  .option("--oak", "backtest a token against the recorded token-series instead of Yahoo daily bars")
  .option("--range <range>", "yahoo range: 1mo 3mo 6mo 1y 2y 5y ytd max", "6mo")
  .option("--budget <usd>", "starting equity", "250")
  .option("--warmup <bars>", "bars before the first decision", "30")
  .option("--json", "machine-readable output")
  .action(async (symbol: string, opts: { oak?: boolean; range: string; budget: string; warmup: string; json?: boolean }) => {
    const rt = boot();
    const { backtest, fetchYahooDaily, readRecordedSeries } = await import("./backtest.js");
    const budget = Number(opts.budget);
    const warmup = Number(opts.warmup);

    let bars;
    let source: "robinhood-mcp" | "chainbridge";
    if (opts.oak) {
      bars = readRecordedSeries(rt.config.home, symbol);
      source = "chainbridge";
      if (bars.length < warmup + 1) {
        fail(
          `only ${bars.length} recorded bar(s) for ${symbol.toUpperCase()} — ` +
            `run \`coral scan ${symbol.toUpperCase()} --oak\` over time to build a real series (needs ${warmup + 1}+).`,
        );
        rt.close();
        process.exit(1);
      }
    } else {
      source = "robinhood-mcp";
      try {
        bars = await fetchYahooDaily(symbol, opts.range);
      } catch (err) {
        fail(`no real history for ${symbol}: ${(err as Error).message}`);
        rt.close();
        process.exit(1);
      }
      if (bars.length < warmup + 1) {
        fail(`yahoo returned ${bars.length} bars for ${symbol} — below the ${warmup + 1}-bar minimum. Try a longer --range.`);
        rt.close();
        process.exit(1);
      }
    }

    const result = backtest({ symbol, bars, source, budget, warmup });
    if (opts.json) {
      console.log(JSON.stringify(result, null, 2));
      rt.close();
      return;
    }
    banner();
    heading(`Backtest · ${result.symbol} · ${result.from} → ${result.to}`);
    keyValue([
      ["source", `${result.source} · ${result.bars} real bars`],
      ["equity", `$${result.startEquity.toFixed(2)} → $${result.endEquity.toFixed(2)} (${result.returnPct >= 0 ? "+" : ""}${result.returnPct.toFixed(1)}%)`],
      ["buy & hold", `${result.buyHoldPct >= 0 ? "+" : ""}${result.buyHoldPct.toFixed(1)}% (${result.vsBuyHold >= 0 ? "+" : ""}${result.vsBuyHold.toFixed(1)}% vs)`],
      ["trades", `${result.trades} · ${result.wins}W/${result.losses}L`],
      ["fees paid", `$${result.feesPaid.toFixed(2)}`],
      ["max drawdown", `${result.maxDrawdownPct.toFixed(1)}%`],
      ...(result.openPosition
        ? [["open", `${result.openPosition.qty.toFixed(6)} ${result.symbol} ≈ $${result.openPosition.markUsd.toFixed(2)}`] as [string, string]]
        : []),
    ]);
    console.log();
    for (const n of result.notes) console.log(`  ${c.dim("·")} ${c.dim(n)}`);
    console.log();
    rt.close();
  });

